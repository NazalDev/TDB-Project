<?php
// product_services.php

header("Access-Control-Allow-Origin: *");
header("Access-Control-Allow-Methods: POST, GET, DELETE, PUT, OPTIONS");
header("Access-Control-Allow-Headers: Content-Type, Access-Control-Allow-Headers, Authorization, X-Requested-With");
header('Content-Type: application/json');
file_put_contents('log.txt', $_SERVER['REQUEST_METHOD'] . " request received at " . date('Y-m-d H:i:s') . "\n", FILE_APPEND);
include 'db_config.php';

$method = $_SERVER['REQUEST_METHOD'];

$romanMonths = [
    1 => 'I', 2 => 'II', 3 => 'III', 4 => 'IV',
    5 => 'V', 6 => 'VI', 7 => 'VII', 8 => 'VIII',
    9 => 'IX', 10 => 'X', 11 => 'XI', 12 => 'XII'
];

if ($method == 'POST') {
    $input = json_decode(file_get_contents('php://input'), true);
    $po_number = $input['po_number'] ?? '';
    $notes = $input['notes'] ?? '';
    $today = date("Y-m-d");
    $month = date("m");
    $year = date("Y");

    // 1. Fetch info and Sanitize strings (remove spaces)
    $infoStmt = $conn->prepare("
        SELECT c.company_short_name, s.site_name 
        FROM purchase_orders po
        JOIN company_sites s ON s.site_id = po.site_id
        JOIN companies c ON s.company_id = c.company_id
        WHERE po.po_number = ?
    ");
    $infoStmt->bind_param("s", $po_number);
    $infoStmt->execute();
    $info = $infoStmt->get_result()->fetch_assoc();

    if (!$info) {
        header('Content-Type: application/json');
        echo json_encode(["status" => "error", "message" => "PO Number not found"]);
        exit;
    }

    // Remove spaces from names to keep the DO number clean
    $compName = str_replace(' ', '', $info['company_short_name']);
    $siteName = str_replace(' ', '', $info['site_name']);

    // 2. Use a Transaction for accuracy
    $conn->begin_transaction();

    try {
        // First, insert with a placeholder DO number
        $stmt = $conn->prepare("INSERT INTO delivery_orders (do_number, po_number, do_date, notes) VALUES (?, ?, ?, ?)");
        $stmt->bind_param("ssss", $po_number, $po_number, $today, $notes);
        $stmt->execute();
        
        // Get the real ID generated by the database
        $realId = $conn->insert_id;
        
        // Romanize the month number
        $romanMonth = $romanMonths[(int)$month];
        
        // Generate the final DO Number
        $do_number = "{$realId}/DO/TDB/{$compName}-{$siteName}/{$romanMonth}/{$year}";

        // Update the record with the final formatted number
        $updateStmt = $conn->prepare("UPDATE delivery_orders SET do_number = ? WHERE do_id = ?");
        $updateStmt->bind_param("si", $do_number, $realId);
        $updateStmt->execute();

        $conn->commit();

        header('Content-Type: application/json');
        echo json_encode([
            "status" => "success", 
            "do_number" => $do_number,
            "id" => $realId
        ]);

    } catch (Exception $e) {
        $conn->rollback();
        header('Content-Type: application/json');
        echo json_encode(["status" => "error", "message" => $e->getMessage(), "id" => $realId, "do_number" => $do_number]);
    }
}

if ($method == 'GET') {
    $search = isset($_GET['search']) ? $_GET['search'] : '';
    
    if ($search !== '') {
        // Mode search
        $stmt = $conn->prepare("SELECT do.do_id, do.do_number, do.do_date, do.notes, po.po_number, po.is_deleted AS po_is_deleted, c.company_short_name, c.company_name, cs.site_name, cs.site_address FROM delivery_orders do JOIN purchase_orders po USING (po_number) JOIN company_sites cs ON po.site_id = cs.site_id JOIN companies c ON c.company_id = cs.company_id WHERE (do_number LIKE ? OR po_number LIKE ? OR do.do_id = ?) AND do.is_deleted = 0");
        $likeTerm = "%" . $search . "%";
        $stmt->bind_param("sss", $likeTerm, $likeTerm, $likeTerm);
        $stmt->execute();
        $result = $stmt->get_result();
    } else {
        // mode get all
        $result = $conn->query("SELECT do.do_id, do.do_number, do.do_date, do.notes, po.po_number, po.is_deleted AS po_is_deleted, c.company_short_name, c.company_name, cs.site_name, cs.site_address FROM delivery_orders do JOIN purchase_orders po USING (po_number) JOIN company_sites cs ON po.site_id = cs.site_id JOIN companies c ON c.company_id = cs.company_id WHERE do.is_deleted = 0");
    }

    $data = [];
    while($row = $result->fetch_assoc()) { 
        $data[] = $row; 
    }
    echo json_encode($data);
}

if ($method == 'DELETE') {
     $id = isset($_GET['search']) ? $_GET['search'] : '';

    if ($id !== '') {
        $stmt = $conn->prepare("UPDATE delivery_orders SET is_deleted = 1, deleted_at = NOW() WHERE do_id = ?");
        $stmt->bind_param("s", $id);
        
        if ($stmt->execute()) {
            if ($stmt->affected_rows > 0) {
                http_response_code(200);
                echo json_encode(["status" => "success", "message" => "Deleted successfully"]);

            } else {
                http_response_code(404);
                echo json_encode(["status" => "error", "message" => "No Po found with Number: $id"]);
            }
        } else {
            http_response_code(400);
            echo json_encode(["status" => "error", "message" => $stmt->error]);
        }
    } else {
        http_response_code(400);
        echo json_encode(["status" => "error", "message" => "Invalid Po Number"]);
    }
    exit;
}

$conn->close();
?>