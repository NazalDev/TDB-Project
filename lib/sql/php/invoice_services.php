<?php
// product_services.php

header("Access-Control-Allow-Origin: *");
header("Access-Control-Allow-Methods: POST, GET, DELETE, PUT, OPTIONS");
header("Access-Control-Allow-Headers: Content-Type, Access-Control-Allow-Headers, Authorization, X-Requested-With");
header('Content-Type: application/json');
file_put_contents('log.txt', $_SERVER['REQUEST_METHOD'] . " request received at " . date('Y-m-d H:i:s') . "\n", FILE_APPEND);
include 'db_config.php';

$method = $_SERVER['REQUEST_METHOD'];

if ($method == 'POST') {
    $input = json_decode(file_get_contents('php://input'), true);
    $do_id = $input['do_id'] ?? '';
    $notes = $input['notes'] ?? '';
    $today = date("Y-m-d");

    try {
        // First, insert with a placeholder DO number
        $stmt = $conn->prepare("INSERT INTO invoices (invoice_number, do_id, invoice_date, due_date, currency, ppn, total_amount, notes) VALUES ( ?, ?, ?, ?, ?, ?, '0', ?)");
        $stmt->bind_param("sssssss", $do_id, $do_id, $today, $input['due_date'], $input['currency'], $input['ppn'], $notes);
        $stmt->execute();
        
        // Get the real ID generated by the database
        $realId = $conn->insert_id;
        
        // insert all of the do items into the invoice
        $sqlItems = $conn->prepare("INSERT INTO invoice_items (invoice_id, product_id, quantity, price, total)
                         SELECT ?, product_id, qty_shipped, unit_price, total 
                         FROM delivery_order_items 
                         WHERE do_id = ?");
        $sqlItems->bind_param("ss", $realId, $do_id);    
        $sqlItems->execute();                     

        // Generate the final Invoice Number
        $invoice_number = "DB{$realId}";

        // Update the record with the final formatted number
        $updateStmt = $conn->prepare("UPDATE invoices SET invoice_number = ? WHERE invoice_id = ?");
        $updateStmt->bind_param("si", $invoice_number, $realId);
        $updateStmt->execute();
        
        $conn->commit();

        header('Content-Type: application/json');
        echo json_encode([
            "status" => "success", 
            "invoice_number" => $invoice_number,
            "invoice_id" => $realId
        ]);

    } catch (Exception $e) {
        $conn->rollback();
        header('Content-Type: application/json');
        echo json_encode(["status" => "error", "message" => $e->getMessage()]);
    }
}



if ($method == 'GET') {
    $search = isset($_GET['search']) ? $_GET['search'] : '';
    
    if ($search !== '') {
        // Mode search
        $stmt = $conn->prepare("SELECT i.invoice_id, i.invoice_number, i.invoice_date, i.due_date, do.po_number, cs.site_name, cs.site_address, c.company_short_name, c.company_name FROM invoices i JOIN delivery_orders do USING (do_id) JOIN purchase_orders USING (po_number) JOIN company_sites cs USING (site_id) JOIN companies c USING (company_id) WHERE i.invoice_number LIKE ? or do.po_number LIKE ? AND i.is_deleted = 0");
        $likeTerm = "%" . $search . "%";
        $stmt->bind_param("ss", $likeTerm, $likeTerm);
        $stmt->execute();
        $result = $stmt->get_result();
    } else {
        // mode get all
        $result = $conn->query("SELECT i.invoice_id, i.invoice_number, i.invoice_date, i.due_date, do.po_number, cs.site_name, cs.site_address, c.company_short_name, c.company_name FROM invoices i JOIN delivery_orders do USING (do_id) JOIN purchase_orders USING (po_number) JOIN company_sites cs USING (site_id) JOIN companies c USING (company_id) WHERE i.is_deleted = 0");
    }

    $data = [];
    while($row = $result->fetch_assoc()) { 
        $data[] = $row; 
    }
    echo json_encode($data);
}

if ($method == 'DELETE') {
     $id = isset($_GET['search']) ? $_GET['search'] : '';

    if ($id !== '') {
        $stmt = $conn->prepare("UPDATE invoices SET is_deleted = 1, deleted_at = NOW() WHERE invoice_number = ?");
        $stmt->bind_param("s", $id);
        
        if ($stmt->execute()) {
            if ($stmt->affected_rows > 0) {
                http_response_code(200);
                echo json_encode(["status" => "success", "message" => "Deleted successfully"]);

            } else {
                http_response_code(404);
                echo json_encode(["status" => "error", "message" => "No Invoice found with Number: $id"]);
            }
        } else {
            http_response_code(400);
            echo json_encode(["status" => "error", "message" => $stmt->error]);
        }
    } else {
        http_response_code(400);
        echo json_encode(["status" => "error", "message" => "Invalid Po Number"]);
    }
    exit;
}

$conn->close();
?>